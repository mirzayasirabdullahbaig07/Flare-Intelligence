"""Document-grounded retrieval (TF-IDF). Works without any paid API.

retrieval mode : sentences copied word-for-word from the retrieved passages (default)
local_llm mode : optional; a local Ollama model may use ONLY the retrieved passages
The answer says "not enough information" when a name in the question is absent from the
documents, the best passage is a weak match, or too few question words are found.
A sentence is shown only if it contains one of the question's most distinctive words.
The score is TF-IDF cosine similarity, not the probability that an answer is true.
"""
from __future__ import annotations

import json
import os
import re
import urllib.error
import urllib.request
from dataclasses import dataclass

import pandas as pd
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS, TfidfVectorizer
from sklearn.metrics.pairwise import linear_kernel

from src.source_manager import citation_label

MIN_SCORE = 0.09      # starting value; not validated beyond a handful of questions
MIN_COVERAGE = 0.5    # share of the question's words that must appear in the top passages
MIN_SENTENCE_WORDS = 8
MAX_SENTENCE_WORDS = 60

INSUFFICIENT_MESSAGE = ("The available documents do not contain enough information "
                        "to answer this question.")
PASSAGES_ONLY_MESSAGE = ("Related passages were found, but no single clean sentence answers the "
                         "question directly. Please read the passages below.")
LABEL_RETRIEVAL = "Matching sentences copied from the documents (not a generated answer)"
LABEL_LLM = "Generated by a local model from the retrieved passages; verify against the sources"

# Search-only word links (shown to the user). They never appear in the answer text.
EXPANSIONS = {
    "habitat": "spacecraft", "habitats": "spacecraft", "moon": "lunar", "mars": "martian",
    "investigated": "objectives", "investigate": "objectives", "purpose": "objectives",
    "hypothesize": "hypothesis", "hypothesized": "hypothesis", "hypothesise": "hypothesis",
}

_HEADER_RE = re.compile(r"NASA/TM-\d+\s+\d+\s+")
_LEADING_NUMBER_RE = re.compile(r"^(?:\d+(?:\.\d+)*[\).]?\s+)+")
_REFERENCE_RE = re.compile(r"^[A-Z][\w'\u2019\-]+,\s+[A-Z][\w.]*(?:\s+[A-Z][\w.]*)*\s*[:;]")


@dataclass
class Hit:
    chunk: dict
    score: float


class Retriever:
    def __init__(self, chunks: list[dict]):
        self.chunks = [c for c in chunks if c.get("text")]
        self.vectorizer = None
        self.matrix = None
        if self.chunks:
            self.vectorizer = TfidfVectorizer(
                stop_words="english", ngram_range=(1, 2), sublinear_tf=True)
            self.matrix = self.vectorizer.fit_transform([c["text"] for c in self.chunks])

    def knows(self, term: str) -> bool:
        """True if this word appears anywhere in the loaded documents."""
        return self.vectorizer is not None and term in self.vectorizer.vocabulary_

    def key_terms(self, text: str, n: int = 2) -> set[str]:
        """The n most distinctive (highest IDF) words of the text that the documents contain."""
        if self.vectorizer is None:
            return set()
        vocab, idf = self.vectorizer.vocabulary_, self.vectorizer.idf_
        known = sorted(((idf[vocab[t]], t) for t in _terms(text) if t in vocab), reverse=True)
        return {t for _, t in known[:n]}

    def search(self, query: str, k: int = 5) -> list[Hit]:
        if self.matrix is None or not query.strip():
            return []
        sims = linear_kernel(self.vectorizer.transform([query]), self.matrix).ravel()
        order = sims.argsort()[::-1][:k]
        return [Hit(self.chunks[i], float(sims[i])) for i in order if sims[i] > 0]


def _terms(text: str) -> set[str]:
    words = re.findall(r"[a-z0-9]+", text.lower())
    return {w for w in words if len(w) > 1 and w not in ENGLISH_STOP_WORDS}


def _split_sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", text) if s.strip()]


def expand_query(question: str) -> tuple[str, list[str]]:
    lowered = question.lower()
    extras = []
    for word in re.findall(r"[a-z]+", lowered):
        extra = EXPANSIONS.get(word)
        if extra and extra not in lowered and extra not in extras:
            extras.append(extra)
    return (question + " " + " ".join(extras)).strip(), extras


def named_terms(question: str) -> list[str]:
    """Capitalised or ALL-CAPS words after the first word (e.g. SAFFIRE, PMMA, France)."""
    tokens = re.findall(r"[A-Za-z][A-Za-z0-9\-]*", question)
    return [t for t in tokens[1:] if t[0].isupper() or t.isupper()]


def missing_names(question: str, retriever: Retriever) -> list[str]:
    missing = []
    for name in named_terms(question):
        parts = _terms(name.replace("-", " "))
        if parts and any(not retriever.knows(p) for p in parts):
            missing.append(name)
    return missing


def term_coverage(question: str, hits: list[Hit], top_chunks: int = 3) -> float:
    terms = _terms(question)
    if not terms or not hits:
        return 0.0
    seen: set[str] = set()
    for hit in hits[:top_chunks]:
        seen |= _terms(hit.chunk["text"])
    return len(terms & seen) / len(terms)


def clean_sentence(sentence: str) -> str | None:
    """Readable sentence, or None for table dumps, fragments and reference entries."""
    s = _HEADER_RE.sub("", sentence.strip())
    s = _LEADING_NUMBER_RE.sub("", s).strip().strip('"\u201c\u201d').strip()
    words = s.split()
    if not (MIN_SENTENCE_WORDS <= len(words) <= MAX_SENTENCE_WORDS):
        return None
    if not s[0].isupper() or s[-1] not in ".!?":
        return None
    if s.count("(") != s.count(")") or s.count(";") >= 2:
        return None
    if _REFERENCE_RE.match(s):
        return None
    if sum(ch.isdigit() for ch in s) / len(s) > 0.10:
        return None
    return s


def extract_sentences(query: str, hits: list[Hit], key_terms: set[str],
                      max_sentences: int = 4, top_chunks: int = 5) -> list[dict]:
    """Readable sentences that contain a key term and share words with the query."""
    terms = _terms(query)
    if not terms:
        return []
    min_overlap = 2 if len(terms) >= 3 else 1
    candidates = []
    for rank, hit in enumerate(hits[:top_chunks]):
        for raw in _split_sentences(hit.chunk["text"]):
            sentence = clean_sentence(raw)
            if not sentence:
                continue
            sentence_terms = _terms(sentence)
            if key_terms and not (key_terms & sentence_terms):
                continue
            overlap = len(terms & sentence_terms)
            if overlap >= min_overlap:
                candidates.append((overlap, -rank, sentence, rank))
    candidates.sort(key=lambda c: (c[0], c[1]), reverse=True)
    chosen, seen = [], set()
    for _, _, sentence, rank in candidates:
        if sentence.lower() in seen:
            continue
        seen.add(sentence.lower())
        chosen.append({"text": sentence, "source_n": rank + 1})
        if len(chosen) >= max_sentences:
            break
    return chosen


# ---------- optional local LLM (Ollama) ----------

def _base_url(base_url: str | None = None) -> str:
    url = base_url or os.environ.get("OLLAMA_HOST", "http://localhost:11434")
    if not url.startswith("http"):
        url = "http://" + url
    return url.rstrip("/")


def list_ollama_models(base_url: str | None = None, timeout: float = 1.5) -> list[str]:
    """Names of locally installed Ollama models, or [] if Ollama is not running."""
    try:
        with urllib.request.urlopen(f"{_base_url(base_url)}/api/tags", timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        return [m["name"] for m in data.get("models", [])]
    except (urllib.error.URLError, OSError, ValueError, KeyError):
        return []


def build_prompt(question: str, hits: list[Hit]) -> str:
    passages = "\n\n".join(f"[{i}] ({h.chunk['doc_title']}, {h.chunk['location']}) {h.chunk['text']}"
                           for i, h in enumerate(hits, start=1))
    return ("You answer questions about NASA microgravity combustion research using ONLY the "
            "numbered passages below. If they do not contain the answer, reply exactly: "
            "INSUFFICIENT EVIDENCE. Cite passage numbers like [1]. Add no facts from outside "
            f"the passages.\n\nPASSAGES:\n{passages}\n\nQUESTION: {question}\nANSWER:")


def generate_with_ollama(question: str, hits: list[Hit], model: str,
                         base_url: str | None = None, timeout: float = 120) -> str | None:
    payload = json.dumps({"model": model, "prompt": build_prompt(question, hits),
                          "stream": False, "options": {"temperature": 0.1}}).encode("utf-8")
    request = urllib.request.Request(f"{_base_url(base_url)}/api/generate", data=payload,
                                     headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as resp:
            text = json.loads(resp.read().decode("utf-8")).get("response", "").strip()
        return text or None
    except (urllib.error.URLError, OSError, ValueError):
        return None


# ---------- main entry point ----------

def _sources(hits: list[Hit], registry: pd.DataFrame, min_score: float) -> list[dict]:
    out = []
    for n, hit in enumerate(hits, start=1):
        c = hit.chunk
        out.append({"n": n, "score": round(hit.score, 3), "low_relevance": hit.score < min_score,
                    "label": f"{c['doc_title']}, {c['location']}",
                    "registry_ref": citation_label(c.get("source_id", ""), registry),
                    "file": c.get("file", ""), "text": c["text"]})
    return out


def answer_question(question: str, retriever: Retriever, registry: pd.DataFrame,
                    k: int = 5, use_llm: bool = False, model: str | None = None,
                    min_score: float = MIN_SCORE) -> dict:
    query, extras = expand_query(question)
    hits = retriever.search(query, k)
    top = hits[0].score if hits else 0.0
    coverage = term_coverage(question, hits)
    key = retriever.key_terms(query)
    result = {"question": question, "mode": "retrieval", "label": LABEL_RETRIEVAL,
              "evidence": "insufficient", "answer": INSUFFICIENT_MESSAGE, "sentences": [],
              "top_score": round(top, 3), "coverage": round(coverage, 2),
              "key_terms": sorted(key), "expanded_with": extras,
              "sources": _sources(hits, registry, min_score), "note": ""}

    missing = missing_names(question, retriever)
    if missing:
        result["note"] = ("These names do not appear anywhere in the loaded documents: "
                          + ", ".join(missing) + ".")
        return result
    if not hits or top < min_score or coverage < MIN_COVERAGE:
        result["note"] = "The best matching passages were too weak a match to rely on."
        return result

    sentences = extract_sentences(query, hits, key)
    if not sentences:
        result["evidence"], result["answer"] = "passages_only", PASSAGES_ONLY_MESSAGE
        return result

    result["evidence"] = "sufficient"
    result["sentences"] = sentences
    result["answer"] = "\n".join(f"- {s['text']} [{s['source_n']}]" for s in sentences)

    if use_llm:
        models = list_ollama_models()
        chosen = model or (models[0] if models else None)
        if not chosen:
            result["note"] = "No local LLM is running; showing sentences taken directly from the documents."
        else:
            text = generate_with_ollama(question, hits[:5], chosen)
            if not text:
                result["note"] = "The local LLM did not respond; showing sentences taken directly from the documents."
            elif "INSUFFICIENT EVIDENCE" in text.upper():
                result["evidence"], result["answer"] = "insufficient", INSUFFICIENT_MESSAGE
                result["sentences"] = []
            else:
                result["mode"], result["label"], result["answer"] = "local_llm", LABEL_LLM, text
                result["note"] = f"Generated by local model '{chosen}' from the passages below. Check it against them."
    return result